export const GLYPH_H = 7;

/** Rows of a glyph, each a 5-character string of "#" and ".". An unknown character throws, so a typo fails loudly. */
export function glyph(ch: string): string[] {
  const g = G[ch];
  if (!g) throw new Error(`font5x7: no glyph for ${JSON.stringify(ch)}`);
  return g.split("|");
}
